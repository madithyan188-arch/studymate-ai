interface LanguageContextType {
  language: Language
  setLanguage: (lang: Language) => void
  t: (key: string, params?: Record<string, string | number>) => string
  supportedLanguages: LanguageOption[]
  quizQuestions: LocalizedQuizQuestion[]
  currentLanguageOption: LanguageOption
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en')
  const [mounted, setMounted] = useState(false)

  // Read stored language on client mount
  useEffect(() => {
    try {
      const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY) as Language | null
      if (stored && ['en', 'ml', 'hi', 'ta'].includes(stored)) {
        setLanguageState(stored)
        document.documentElement.lang = stored
      } else {
        document.documentElement.lang = 'en'
      }
    } catch {
      // Ignore storage access errors
    }
    setMounted(true)
  }, [])

  const setLanguage = (newLang: Language) => {
    setLanguageState(newLang)
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, newLang)
    } catch {
      // Ignore storage errors
    }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = newLang
    }
  }

  const t = (key: string, params?: Record<string, string | number>): string => {
    const langDict = translations[language] || translations.en
    let text = langDict[key] ?? translations.en[key] ?? key

    if (params) {
      Object.entries(params).forEach(([paramKey, paramVal]) => {
        text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal))
      })
    }

    return text
  }

  const quizQuestions = useMemo(() => {
    return LOCALIZED_QUIZ_QUESTIONS[language] || LOCALIZED_QUIZ_QUESTIONS.en
  }, [language])

  const currentLanguageOption = useMemo(() => {
    return SUPPORTED_LANGUAGES.find((l) => l.code === language) || SUPPORTED_LANGUAGES[0]
  }, [language])

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        t,
        supportedLanguages: SUPPORTED_LANGUAGES,
        quizQuestions,
        currentLanguageOption,
      }}
    >
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    // Graceful fallback for components rendered outside provider
    const fallbackLang: Language = 'en'
    return {
      language: fallbackLang,
      setLanguage: () => {},
      t: (key: string, params?: Record<string, string | number>) => {
        let text = translations.en[key] ?? key
        if (params) {
          Object.entries(params).forEach(([paramKey, paramVal]) => {
            text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal))
          })
        }
        return text
      },
      supportedLanguages: SUPPORTED_LANGUAGES,
      quizQuestions: LOCALIZED_QUIZ_QUESTIONS.en,
      currentLanguageOption: SUPPORTED_LANGUAGES[0],
    }
  }
  return context
}
